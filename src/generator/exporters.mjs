/**
 * OneForge Sledge — Multi-Format Design Token Exporters
 * Compiles DesignSystem tokens into CSS Custom Properties, Tailwind Config, W3C DTCG JSON, and SCSS.
 */

/**
 * Exports tokens as clean CSS Custom Properties (:root stylesheet).
 */
export function exportToCssVariables(system) {
  const lines = [
    `/**`,
    ` * ${system.name} Design System — CSS Custom Properties`,
    ` * Generated by OneForge Sledge (https://oneforge.dev)`,
    ` */`,
    `:root {`,
  ];

  const colors = system.tokens?.colors || {};
  lines.push('  /* Colors */');
  for (const [key, val] of Object.entries(colors)) {
    if (typeof val === 'string' && val.startsWith('#')) {
      lines.push(`  --color-${key}: ${val};`);
    }
  }

  const typography = system.tokens?.typography || {};
  lines.push('\n  /* Typography */');
  const seenFonts = new Set();
  for (const [key, rule] of Object.entries(typography)) {
    if (rule.fontFamily && !seenFonts.has(rule.fontFamily)) {
      seenFonts.add(rule.fontFamily);
      lines.push(`  --font-family-primary: ${rule.fontFamily};`);
    }
    if (rule.fontSize) lines.push(`  --font-size-${key}: ${rule.fontSize};`);
    if (rule.lineHeight) lines.push(`  --line-height-${key}: ${rule.lineHeight};`);
  }

  const spacing = system.tokens?.spacing || {};
  lines.push('\n  /* Spacing */');
  for (const [key, val] of Object.entries(spacing)) {
    lines.push(`  --spacing-${key}: ${val};`);
  }

  const rounded = system.tokens?.rounded || {};
  lines.push('\n  /* Border Radii */');
  for (const [key, val] of Object.entries(rounded)) {
    lines.push(`  --radius-${key}: ${val};`);
  }

  lines.push('}\n');
  return lines.join('\n');
}

/**
 * Exports tokens as a Tailwind CSS theme extension module.
 */
export function exportToTailwind(system) {
  const colors = system.tokens?.colors || {};
  const spacing = system.tokens?.spacing || {};
  const rounded = system.tokens?.rounded || {};
  const typography = system.tokens?.typography || {};

  const cleanColors = {};
  for (const [k, v] of Object.entries(colors)) {
    if (typeof v === 'string' && v.startsWith('#')) {
      cleanColors[k] = v;
    }
  }

  const primaryFont = Object.values(typography)[0]?.fontFamily || 'system-ui, sans-serif';
  const fontFamilies = primaryFont.split(',').map((f) => f.trim().replace(/['"]/g, ''));

  const tailwindConfig = {
    theme: {
      extend: {
        colors: cleanColors,
        spacing,
        borderRadius: rounded,
        fontFamily: {
          sans: fontFamilies,
        },
      },
    },
  };

  return `/**
 * ${system.name} Design System — Tailwind CSS Preset
 * Generated by OneForge Sledge
 */
module.exports = ${JSON.stringify(tailwindConfig, null, 2)};\n`;
}

/**
 * Exports tokens conforming to the W3C Design Tokens Community Group (DTCG) specification.
 */
export function exportToDtcgJson(system) {
  const dtcg = {
    $name: system.name,
    $description: system.description,
    $version: '1.0.0',
    $generator: 'OneForge Sledge',
    color: {},
    spacing: {},
    borderRadius: {},
    typography: {},
  };

  const colors = system.tokens?.colors || {};
  for (const [key, val] of Object.entries(colors)) {
    if (typeof val === 'string' && val.startsWith('#')) {
      dtcg.color[key] = {
        $value: val,
        $type: 'color',
      };
    }
  }

  const spacing = system.tokens?.spacing || {};
  for (const [key, val] of Object.entries(spacing)) {
    dtcg.spacing[key] = {
      $value: val,
      $type: 'dimension',
    };
  }

  const rounded = system.tokens?.rounded || {};
  for (const [key, val] of Object.entries(rounded)) {
    dtcg.borderRadius[key] = {
      $value: val,
      $type: 'dimension',
    };
  }

  const typography = system.tokens?.typography || {};
  for (const [key, rule] of Object.entries(typography)) {
    dtcg.typography[key] = {
      $type: 'typography',
      $value: {
        fontFamily: rule.fontFamily,
        fontSize: rule.fontSize,
        fontWeight: rule.fontWeight,
        lineHeight: rule.lineHeight,
      },
    };
  }

  return JSON.stringify(dtcg, null, 2);
}

/**
 * Exports tokens as SCSS variables.
 */
export function exportToScss(system) {
  const lines = [
    `// ${system.name} Design System — SCSS Variables`,
    `// Generated by OneForge Sledge`,
    ``,
  ];

  const colors = system.tokens?.colors || {};
  lines.push('// Colors');
  for (const [k, v] of Object.entries(colors)) {
    if (typeof v === 'string' && v.startsWith('#')) {
      lines.push(`$color-${k}: ${v};`);
    }
  }

  const spacing = system.tokens?.spacing || {};
  lines.push('\n// Spacing');
  for (const [k, v] of Object.entries(spacing)) {
    lines.push(`$spacing-${k}: ${v};`);
  }

  const rounded = system.tokens?.rounded || {};
  lines.push('\n// Border Radii');
  for (const [k, v] of Object.entries(rounded)) {
    lines.push(`$radius-${k}: ${v};`);
  }

  return lines.join('\n') + '\n';
}

/**
 * Universal exporter dispatcher.
 */
export function exportTokens(system, format = 'css') {
  switch (format.toLowerCase()) {
    case 'css':
    case 'css-variables':
      return { format: 'css', mimeType: 'text/css', content: exportToCssVariables(system) };
    case 'tailwind':
    case 'tailwind-config':
      return { format: 'tailwind', mimeType: 'application/javascript', content: exportToTailwind(system) };
    case 'json':
    case 'dtcg':
    case 'design-tokens':
      return { format: 'dtcg-json', mimeType: 'application/json', content: exportToDtcgJson(system) };
    case 'scss':
    case 'sass':
      return { format: 'scss', mimeType: 'text/x-scss', content: exportToScss(system) };
    default:
      throw new Error(`Unsupported export format: "${format}". Supported: css, tailwind, dtcg, scss`);
  }
}
